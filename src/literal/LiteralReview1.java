package literal;

public class LiteralReview1 {
    public static void main(String[] args) {
        //写出我的名字，血型，年龄，身高，是否为学生（要用变量来写）
        String name = "Liyi";//我的名字
        System.out.println(name);//表达出我的名字
        String bloodType = "O";//用变量写出我的血型
        System.out.println(bloodType);//表达出我的血型
        int age = 19;//用变量写出我的年龄
        System.out.println(age);//表达出我的年龄
        double height = 1.75;//用变量写出我的身高
        System.out.println(height);//表达出我的身高
        boolean isStudent = true;//是否为学生
        System.out.println(isStudent);//表达出我是否为学生




    }
}
